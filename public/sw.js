/*
 * Service worker da RecFace.
 * Guarda em cache os modelos de reconhecimento (~12 MB) e os arquivos com hash
 * do build, para a portaria abrir rápido nas próximas vezes e aguentar uma
 * oscilação de rede. As páginas e a API sempre vêm da rede.
 */
const CACHE = "recface-v1";

self.addEventListener("install", () => self.skipWaiting());

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("recface-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (!url.pathname.startsWith("/models/") && !url.pathname.startsWith("/assets/")) return;

  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      const hit = await cache.match(req);
      if (hit) return hit;
      const res = await fetch(req);
      if (res.ok) cache.put(req, res.clone());
      return res;
    })
  );
});
